#!/usr/bin/env node
// Generates src/data/roadmap.ts from docs/dsa-pattern-roadmap.md.
// Run: npm run roadmap:generate   (re-run whenever the markdown changes)
//
// Only writes src/data/roadmap.ts. Never touches topics.ts or the Zoho data files.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MD_PATH = join(root, 'docs', 'dsa-pattern-roadmap.md');
const OUT_PATH = join(root, 'src', 'data', 'roadmap.ts');

// LeetCode slugs that can't be derived from the title
const SLUG_OVERRIDES = {
  50: 'powx-n',
};

function slugify(title) {
  return title
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function parseWeeks(label) {
  // "Week 3" | "Weeks 15–16" | "Mix in from Week 19"
  const range = label.match(/Weeks?\s+(\d+)\s*[–-]\s*(\d+)/);
  if (range) return { weekStart: Number(range[1]), weekEnd: Number(range[2]) };
  const single = label.match(/Week\s+(\d+)/);
  if (single) return { weekStart: Number(single[1]), weekEnd: Number(single[1]) };
  throw new Error(`Cannot parse week from "${label}"`);
}

const md = readFileSync(MD_PATH, 'utf8');
const lines = md.split('\n');

const topics = [];
let current = null;
const errors = [];

lines.forEach((line, i) => {
  const heading = line.match(/^## (\d+)\. (.+?) · (.+)$/);
  if (heading) {
    current = {
      id: Number(heading[1]),
      name: heading[2].trim(),
      weekLabel: heading[3].trim(),
      ...parseWeeks(heading[3]),
      recognise: '',
      coreIdea: '',
      notes: [],
      problems: [],
    };
    topics.push(current);
    return;
  }
  if (line.startsWith('## ')) { current = null; return; } // e.g. "## How to use", "## Totals"
  if (!current) return;

  const recognise = line.match(/^\*\*Recognise it:\*\*\s*(.+)$/);
  if (recognise) { current.recognise = recognise[1].trim(); return; }
  const coreIdea = line.match(/^\*\*Core idea:\*\*\s*(.+)$/);
  if (coreIdea) { current.coreIdea = coreIdea[1].trim(); return; }
  // Free-form guidance (topic 20 uses bullets instead of Recognise/Core idea)
  const bullet = line.match(/^- (.+)$/);
  if (bullet) { current.notes.push(bullet[1].trim()); return; }
  if (/^Also overlap with/.test(line)) { current.notes.push(line.trim()); return; }

  // Table rows: | LC | Problem | Level | Core |
  if (/^\|\s*\d+\s*\|/.test(line)) {
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    const [lcStr, title, level, core] = cells;
    if (cells.length !== 4 || !['Easy', 'Medium', 'Hard'].includes(level) || !['', '★'].includes(core)) {
      errors.push(`line ${i + 1}: unexpected row: ${line}`);
      return;
    }
    const lc = Number(lcStr);
    current.problems.push({
      lc,
      title,
      level,
      core: core === '★',
      topicId: current.id,
      url: `https://leetcode.com/problems/${SLUG_OVERRIDES[lc] ?? slugify(title)}/`,
    });
  }
});

// ── Validation ──
const seen = new Map();
topics.forEach((t) => {
  if (!t.problems.length) errors.push(`topic ${t.id} "${t.name}" has no problems`);
  if (!t.recognise && !t.notes.length) errors.push(`topic ${t.id} "${t.name}" has no "Recognise it" or notes`);
  t.problems.forEach((p) => {
    if (seen.has(p.lc)) errors.push(`LC ${p.lc} appears in topic ${seen.get(p.lc)} and ${t.id}`);
    seen.set(p.lc, t.id);
  });
});
if (errors.length) {
  console.error('Roadmap parse failed:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// ── Emit ──
const header = `// AUTO-GENERATED by scripts/parse-roadmap.mjs from docs/dsa-pattern-roadmap.md.
// Do not edit by hand — edit the markdown and run: npm run roadmap:generate
`;

const body = `
export interface RoadmapProblem {
  lc: number;
  title: string;
  level: 'Easy' | 'Medium' | 'Hard';
  core: boolean; // ★
  topicId: number; // roadmap topic id (1–20), not a tracker topic id
  url: string;
}

export interface RoadmapTopic {
  id: number;
  name: string;
  weekLabel: string;
  weekStart: number; // week number in the 24-week plan
  weekEnd: number;
  recognise: string; // '' when the topic only has notes
  coreIdea: string;
  notes: string[]; // extra guidance lines (bullets) — markdown bold kept as **text**
  problems: RoadmapProblem[];
}

/** Week 1 of the 24-week plan starts on this Saturday. */
export const PLAN_START_DATE = '2026-10-17';

export const ROADMAP_TOPICS: RoadmapTopic[] = ${JSON.stringify(topics, null, 2)};
`;

writeFileSync(OUT_PATH, header + body);

const all = topics.flatMap((t) => t.problems);
console.log(`Wrote ${OUT_PATH.replace(root + '/', '')}`);
console.log(`  topics:   ${topics.length}`);
console.log(`  problems: ${all.length}`);
console.log(`  core (★): ${all.filter((p) => p.core).length}`);
